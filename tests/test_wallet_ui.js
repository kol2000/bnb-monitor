// Run with node tests/test_wallet_ui.js; test actual functions without browser/network.
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('static/app.js','utf8');
const elements={'wallet-search':{value:''},'wallet-filter':{value:'all'}};
const context={$,usdtEnabled:true,staleAfter:180,Date,Math,BigInt,escapeHtml:s=>String(s),date:s=>String(s)};
function $(id){return elements[id];}
vm.createContext(context);
const filters=source.slice(source.indexOf('function matchesWalletSearch'),source.indexOf("$('wallet-search').oninput"));
const fresh=source.slice(source.indexOf('function checkLine'),source.indexOf('function renderWallets'));
vm.runInContext(filters+'\n'+fresh,context);
const w={name:'User@example.com',address:'0x1234567890',balance:'1000000000000000001',usdt_balance:'0'};
elements['wallet-search'].value='EXAMPLE';assert(context.matchesWalletSearch(w));
elements['wallet-search'].value='absent';assert(!context.matchesWalletSearch(w));
elements['wallet-search'].value='';elements['wallet-filter'].value='bnb';assert(context.matchesWalletSearch(w));
elements['wallet-filter'].value='usdt';assert(!context.matchesWalletSearch(w));
elements['wallet-filter'].value='unnamed';assert(context.matchesWalletSearch({...w,name:w.address.slice(0,8)}));
elements['wallet-filter'].value='error';assert(context.matchesWalletSearch({...w,error:'timeout'}));
assert(context.checkLine('BNB',Date.now()/1000-600,'').includes('устарел'));
assert(context.checkLine('BNB',Date.now()/1000,'timeout').includes('Последний успешный баланс сохранён'));
assert(context.checkLine('USDT',0,'',false).includes('Выключен'));
console.log('Wallet search, filters and freshness: OK');
vm.runInContext('let activeWithdrawals=[],confirmingWallet=null,withdrawalBusy=false;\n'+source.slice(source.indexOf('function walletWithdrawalControl'),source.indexOf('function renderWallets')),context);
const row={id:1,address:'0xabc',balance:'1'};
assert(!context.walletWithdrawalControl(row).includes('Вывод в процессе'));
vm.runInContext("activeWithdrawals=[{wallet_id:1,source:'0xabc',middle:'0xdef',legs:2,state:'pending1'}]",context);
assert(context.walletWithdrawalControl({...row,balance:'0'}).includes('1/2: на аккаунт 2'));
assert(context.walletWithdrawalControl(row).includes('disabled'));
vm.runInContext("activeWithdrawals[0].state='pending2'",context);
assert(context.walletWithdrawalControl(row).includes('2/2: на биржу'));
assert(context.walletWithdrawalControl({id:2,address:'0xdef',balance:'0'}).includes('Вывод в процессе'));
vm.runInContext("activeWithdrawals[0].legs=1;activeWithdrawals[0].state='pending1'",context);
assert(context.walletWithdrawalControl(row).includes('Вывод в процессе · на биржу'));
vm.runInContext("activeWithdrawals[0].state='blocked'",context);
assert(context.walletWithdrawalControl(row).includes('приостановлен'));
vm.runInContext('activeWithdrawals=[]',context);
assert.strictEqual(context.walletWithdrawalControl({...row,balance:'0'}),'');
console.log('Wallet withdrawal progress: OK');
vm.runInContext("activeWithdrawals=[{wallet_id:1,source:'0xabc',middle:'0xdef',legs:2,state:'done',updated:100}]",context);
let completed=context.walletWithdrawalControl({...row,checked:90});
assert(completed.includes('Выведено · баланс обновляется'));
assert(completed.includes('disabled'));
completed=context.walletWithdrawalControl({...row,checked:101,balance:'0'});
assert(completed.includes('✓ Выведено'));
assert(completed.includes('disabled'));
completed=context.walletWithdrawalControl({...row,checked:101,balance:'100'});
assert(completed.includes('Последний вывод завершён'));
assert(!completed.includes('disabled'));
assert(context.walletWithdrawalControl({...row,checked:101,error:'timeout'}).includes('disabled'));
console.log('Completed withdrawals remain visible until and after balance refresh: OK');

vm.runInContext('let hideSmallBalances=true;\n'+source.slice(source.indexOf('function matchesBalanceFilter'),source.indexOf('function compareWallets')),context);
assert(!context.matchesBalanceFilter({usdt_balance:'999999999999999999',bnb_at_least_dollar:false,usd:'$1.00'}));
assert(context.matchesBalanceFilter({usdt_balance:'1000000000000000000',bnb_at_least_dollar:false}));
assert(context.matchesBalanceFilter({usdt_balance:'0',bnb_at_least_dollar:true}));
assert(!context.matchesBalanceFilter({usdt_balance:null,bnb_at_least_dollar:false}));
context.usdtEnabled=false;assert(!context.matchesBalanceFilter({usdt_balance:'2000000000000000000',bnb_at_least_dollar:false}));
console.log('One-dollar wallet filter boundaries: OK');
